    @staticmethod
    def _require_class_name(name: str) -> None:
        if not name:
            raise ScaffoldError(
                "a suite class name is required; pass a class name like WidgetSuite"
            )
        if not name.isidentifier() or keyword.iskeyword(name) or not name[0].isupper():
            raise ScaffoldError(
                f"{name!r} is not a suite class name; pass a class name like WidgetSuite"
            )
